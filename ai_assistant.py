import os 
from dotenv import load_dotenv
from tools import Tools,FUNCTION_NAME_TO_FUNCTION
import ollama


load_dotenv()
ollama_host = os.getenv("host")
model_name = os.getenv("MODE")  

client = ollama.Client(host=ollama_host)
print("Sending request to local model...")

messages = []
messages.append( 
    {
        'role': 'system',
        'content': "Always respond in 20 words or less. If you don't know the answer, say 'I don't know'."
    }
)

while True:
    user_input = input("\nAbhishek:  ")
    
    if user_input.lower() in ["exit", "quit"]:
        print("Exiting...")
        break
    
    messages.append(
        { 
            'role': 'user',
            'content': user_input
        }
    )
    
    # Chained tool-calling loop (handles 1 or multiple tool calls automatically)
    while True:
        response = client.chat(
            model=model_name,
            messages=messages,
            tools=Tools
        )
        msg = response.message
        
        # If the model didn't request a tool, it's ready to give the final answer
        if not msg.tool_calls:
            break
            
        # 1. Append the assistant's tool-call request to history FIRST
        messages.append(msg)
        
        # 2. Execute each requested tool and append the results
        for tool_call in msg.tool_calls:
            func_name = tool_call.function.name
            func_args = tool_call.function.arguments 
            
            fn = FUNCTION_NAME_TO_FUNCTION.get(func_name)
            if fn:
                result = fn(**func_args)
            else:
                result = f"Function {func_name} not found"
            
            messages.append(
                {
                    'role': 'tool',
                    'content': str(result)
                }
            )   
        # The loop automatically repeats: sends the tool output back to the model 
        # so it can either call the next tool or write the final response.

    messages.append(
        {
            "role": 'assistant',
            "content": msg.content
        }
    )
    print("Assistant: " + msg.content)

   


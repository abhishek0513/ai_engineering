import os 
from dotenv import load_dotenv
import ollama


load_dotenv()
ollama_host = os.getenv("host")
model_name = os.getenv("MODE")  

client = ollama.Client(host=ollama_host)
print("Sending request to local model...")

messages = []
messages.append( 
    {
        'role': 'system',
        'content': "Always respond in 20 words or less. If you don't know the answer, say 'I don't know'."
    }
)

while True:
    user_input = input("\nAbhishek:  ")
    
    if(user_input.lower() in ["exit", "quit"]):
        print("Exiting...")
        break
    
    messages.append(
        { 
            'role': 'user',
            'content': user_input
        }
    )
    
    
    response = client.chat( #client.chat.completions.create
        model=model_name,
        messages=messages
    )

    messages.append(
        {
            'role': 'assistant',
            'content': response['message']['content']
        }
    )
    # print("Response received!")
    # print(f"Generated by model: {response.get('model')}")
    # print(f"Generated by model: {response.get('model')}")
    # print(f"Message Role: {response['message']['role']}")
    print("Assistant: "+ response['message']['content'])
    

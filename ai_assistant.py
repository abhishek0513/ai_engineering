import json
import os 
from dotenv import load_dotenv
from tools import Tools,FUNCTION_NAME_TO_FUNCTION
import ollama


load_dotenv()
ollama_host = os.getenv("host")
model_name = os.getenv("MODE")  

client = ollama.Client(host=ollama_host)
print("Sending request to local model...")

messages = []
messages.append( 
    {
        'role': 'system',
        'content': "Always respond in 20 words or less. If you don't know the answer, say 'I don't know'."
    }
)

while True:
    user_input = input("\nAbhishek:  ")
    
    if(user_input.lower() in ["exit", "quit"]):
        print("Exiting...")
        break
    
    messages.append(
        { 
            'role': 'user',
            'content': user_input
        }
    )
    
    
    response = client.chat( #client.chat.completions.create
        model=model_name,
        messages=messages,
        tools = Tools
    )
    msg = response.message
    if msg.tool_calls:
        messages.append(msg)
        for tool_call in msg.tool_calls:
            func_name = tool_call.function.name
            func_args = tool_call.function.arguments #json.loads(tool_call.function.arguments)
            
            fn =  FUNCTION_NAME_TO_FUNCTION.get(func_name)
            result = fn(**func_args)
            
            if fn:
                result = fn(**func_args)
            else:
                result = f"Function {func_name} not found"
            
            messages.append(
                {
                    'role': 'tool',
                    'content': str(result)
                }
            )   
            
        #2nd call to LLM API
        response = client.chat( #client.chat.completions.create
            model=model_name,
            messages=messages,
        )
        
        msg = response.message
    
    messages.append(
        {
            "role" : 'assistant',
            "content" : msg.content
        }
    )
    print("Assistant: "+ msg.content)


